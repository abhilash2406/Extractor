/**
 * Dynamically injects Google Font link into document head on demand
 */
export const loadGoogleFont = (fontFamilyValue) => {
  if (!fontFamilyValue || typeof document === 'undefined') return;
  const primaryName = fontFamilyValue.split(',')[0].replace(/['"]/g, '').trim();
  const linkId = `gfont-${primaryName.toLowerCase().replace(/[^a-z0-9]/g, '-')}`;
  if (document.getElementById(linkId)) return;

  const link = document.createElement('link');
  link.id = linkId;
  link.rel = 'stylesheet';
  link.href = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(primaryName)}:ital,wght@0,300;0,400;0,500;0,600;0,700;1,400&display=swap`;
  document.head.appendChild(link);
};

